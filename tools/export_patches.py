"""Write the handheld's sounds (synth.py PATCHES, LEAD_PATCHES, DRONE_PATCHES) as C++
for the Bricklab Studio plugin: plugin/Source/core/PatchData.h. Run it after changing
a patch:  python3 tools/export_patches.py"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "brickchord"))
import synth  # noqa: E402

WAVE = {"saw": "Saw", "square": "Square", "pulse": "Pulse", "tri": "Tri", "sine": "Sine", "vox": "Vox"}
ENG = {"va": "VA", "fm": "FM", "pluck": "Pluck", "noise": "Noise"}


def f(x):
    return repr(float(x)) + "f"


def patch(p, group):
    eng = p.get("engine", "va")
    oscs = ", ".join("{Wave::%s, %s, %s, %s, %d}" % (WAVE[w], f(c), f(l), f(pn), int(o)) for w, c, l, pn, o in p["oscs"])
    fm = p.get("fm") or {}
    pk = p.get("pluck") or {}
    nz = p["noise"] if isinstance(p.get("noise"), dict) else {}
    nzf = p["noise"] if isinstance(p.get("noise"), (int, float)) else 0.0
    return ("    {\"%s\", %d, Engine::%s, {%s},\n"
            "     %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,\n"
            "     {%s, %s, %s, %s, %s}, {%s, %s, %s}, {%s, %s, %s}}" % (
                p["name"], group, ENG[eng], oscs,
                f(p["cutoff"]), f(p["res"]), f(p["fenv"]), f(p["fa"]), f(p["fd"]), f(p["fs"]),
                f(p["a"]), f(p["d"]), f(p["s"]), f(p["r"]), f(p.get("pwm", 0)), f(p.get("gain", 1.0)),
                "true" if p.get("ladder") else "false", f(p.get("drive", 0)), f(nzf),
                "true" if p.get("noise_dark") else "false",
                f(fm.get("ratio", 1)), f(fm.get("idx", 0)), f(fm.get("idx_s", 0)), f(fm.get("idx_t", 0.1)), f(fm.get("det", 0)),
                f(pk.get("bright", 0.5)), f(pk.get("t60", 1)), f(pk.get("body", 0)),
                f(nz.get("width", 0.05)), f(nz.get("tilt", 1)), f(nz.get("floor", 0.05))))


banks = [(synth.PATCHES, 0), (synth.LEAD_PATCHES, 1), (synth.DRONE_PATCHES, 2)]
rows = [patch(p, g) for bank, g in banks for p in bank]
out = os.path.join(ROOT, "plugin", "Source", "core", "PatchData.h")
with open(out, "w") as fh:
    fh.write("// Generated by tools/export_patches.py from brickchord/synth.py. Do not edit by hand.\n")
    fh.write("#pragma once\n#include \"Patch.h\"\n\nnamespace brick {\n\n")
    fh.write("// group 0: chord sounds, 1: lead sounds, 2: drone sounds (Brickchord's 41, in its order)\n")
    fh.write("static const Patch kPatches[] = {\n" + ",\n".join(rows) + "\n};\n")
    fh.write("static constexpr int kNumPatches = %d;\n\n}  // namespace brick\n" % len(rows))
print("wrote", out, len(rows), "sounds")
